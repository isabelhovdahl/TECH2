# Comments start with a "#" — Python ignores them.
# They're notes for humans, not instructions for the computer.

# Numbers: whole numbers (int) and decimal numbers (float)
students = 24  # int
average_grade = 7.8  # float

# Text: strings, written inside quotes
course_name = "Introduction to Programming"

# Basic math
total_weeks = 11
weeks_remaining = total_weeks - 1

# print() displays things in the terminal
print("Course:", course_name)
print("Students enrolled:", students)
print("Average grade so far:", average_grade)
print("Weeks remaining:", weeks_remaining)
